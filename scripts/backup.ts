import { Database } from "bun:sqlite";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const FORMAT = "mantra-backup-v1";
const AAD = new TextEncoder().encode(FORMAT);

export interface BackupManifest {
  format: typeof FORMAT;
  exportStartedAt: string;
  exportCompletedAt: string;
  source: string;
  sqlSha256: string;
  summary: ReturnType<typeof inspectDatabase>;
  sql: string;
}

export function inspectDatabase(database: Database) {
  const integrity = database.query("PRAGMA integrity_check").all() as { integrity_check: string }[];
  if (integrity.length !== 1 || integrity[0]?.integrity_check !== "ok") {
    throw new Error("SQLite integrity_check failed");
  }
  if (database.query("PRAGMA foreign_key_check").all().length > 0) {
    throw new Error("SQLite foreign_key_check failed");
  }
  const tables = database.query(`SELECT name FROM sqlite_schema
    WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name`).all() as { name: string }[];
  if (!tables.some((table) => table.name === "contributions")) {
    throw new Error("The SQL dump does not contain the mantra contributions table");
  }
  const counts: Record<string, number> = {};
  for (const { name } of tables) {
    const tableName = '"' + name.replaceAll('"', '""') + '"';
    counts[name] = (database.query(`SELECT COUNT(*) AS count FROM ${tableName}`).get() as { count: number }).count;
  }
  const totals = database.query(`SELECT campaign_id, CAST(COALESCE(SUM(effective_amount), 0) AS TEXT) AS total
    FROM contributions GROUP BY campaign_id ORDER BY campaign_id`).all() as { campaign_id: string; total: string }[];
  return { counts, totals };
}

export async function backupKey() {
  const encoded = process.env.BACKUP_KEY_BASE64;
  if (!encoded || !/^[A-Za-z0-9+/]{43}=$/.test(encoded)) {
    throw new Error("BACKUP_KEY_BASE64 must contain exactly 32 random bytes encoded as base64");
  }
  const bytes = Buffer.from(encoded, "base64");
  return crypto.subtle.importKey("raw", bytes, "AES-GCM", false, ["encrypt", "decrypt"]);
}

export async function packBackup(sql: string, source: string, exportStartedAt: string, output: string) {
  if (await Bun.file(output).exists()) throw new Error("Backup output already exists; choose a new filename");
  const database = new Database(":memory:");
  // The dump is generated by our own database export. Rebuild it before trusting this backup.
  database.exec(sql);
  const summary = inspectDatabase(database);
  database.close();
  const manifest: BackupManifest = {
    format: FORMAT,
    exportStartedAt,
    exportCompletedAt: new Date().toISOString(),
    source,
    sqlSha256: new Bun.CryptoHasher("sha256").update(sql).digest("hex"),
    summary,
    sql,
  };
  const iv = crypto.getRandomValues(new Uint8Array(12));
  const ciphertext = await crypto.subtle.encrypt(
    { name: "AES-GCM", iv, additionalData: AAD },
    await backupKey(),
    Bun.gzipSync(new TextEncoder().encode(JSON.stringify(manifest))),
  );
  await Bun.write(output, JSON.stringify({
    format: FORMAT,
    iv: Buffer.from(iv).toString("base64"),
    ciphertext: Buffer.from(ciphertext).toString("base64"),
  }));
  return { ...manifest, sql: undefined };
}

export async function readBackup(path: string): Promise<BackupManifest> {
  const envelope: unknown = await Bun.file(path).json();
  if (typeof envelope !== "object" || envelope === null || !("format" in envelope)
    || envelope.format !== FORMAT || !("iv" in envelope) || typeof envelope.iv !== "string"
    || !("ciphertext" in envelope) || typeof envelope.ciphertext !== "string") {
    throw new Error("Invalid backup envelope");
  }
  const iv = Buffer.from(envelope.iv, "base64");
  if (iv.length !== 12) throw new Error("Invalid backup nonce");
  // AES-GCM authentication fails before SQL is used if the key or archive is wrong.
  const plaintext = await crypto.subtle.decrypt(
    { name: "AES-GCM", iv, additionalData: AAD },
    await backupKey(),
    Buffer.from(envelope.ciphertext, "base64"),
  );
  const manifest = JSON.parse(new TextDecoder().decode(Bun.gunzipSync(new Uint8Array(plaintext)))) as BackupManifest;
  if (manifest.format !== FORMAT || typeof manifest.sql !== "string"
    || !Number.isFinite(Date.parse(manifest.exportStartedAt))
    || !Number.isFinite(Date.parse(manifest.exportCompletedAt))
    || new Bun.CryptoHasher("sha256").update(manifest.sql).digest("hex") !== manifest.sqlSha256) {
    throw new Error("Invalid authenticated backup manifest or SQL checksum");
  }
  return manifest;
}

if (import.meta.main) {
  const [mode, input, output, envFlag, environment] = Bun.argv.slice(2);
  if (!input || !output || !["pack", "remote"].includes(mode ?? "")
    || (envFlag !== undefined && (envFlag !== "--env" || !environment)) || Bun.argv.length > 7) {
    throw new Error("Usage: bun scripts/backup.ts pack <dump.sql> <backup.mantra> | remote <database> <backup.mantra> [--env production]");
  }
  await backupKey();
  const exportStartedAt = mode === "pack" ? process.env.BACKUP_EXPORT_STARTED_AT : new Date().toISOString();
  if (!exportStartedAt || !/T.*(?:Z|[+-]\d{2}:\d{2})$/.test(exportStartedAt)
    || !Number.isFinite(Date.parse(exportStartedAt)) || Date.parse(exportStartedAt) > Date.now()) {
    throw new Error("For an existing dump set BACKUP_EXPORT_STARTED_AT to the true export start ISO time with timezone; do not use the packing time");
  }
  if (mode === "pack") {
    console.log(JSON.stringify(await packBackup(await Bun.file(input).text(), "provided-sql", exportStartedAt, output), null, 2));
  } else {
    const directory = await mkdtemp(join(tmpdir(), "mantra-export-"));
    const sqlFile = join(directory, "database.sql");
    const command = [process.execPath, resolve("node_modules/wrangler/bin/wrangler.js"), "d1", "export", input,
      "--remote", "--skip-confirmation", "--output", sqlFile, ...(environment ? ["--env", environment] : [])];
    try {
      const child = Bun.spawn(command, { stdout: "inherit", stderr: "inherit", env: process.env });
      if (await child.exited !== 0) throw new Error("Wrangler export failed; no backup was created");
      console.log(JSON.stringify(await packBackup(await Bun.file(sqlFile).text(), `d1:${input}`, exportStartedAt, output), null, 2));
    } finally {
      // Only this newly-created private temporary directory is removed.
      await rm(directory, { recursive: true, force: true });
    }
  }
}
