import type { Config, Contribution } from "./types";

export const number = (value: string | number | bigint) => BigInt(value).toString().replace(/\B(?=(\d{3})+(?!\d))/g, " ");
export function dateText(ms: number | null, config: Config) {
  return ms === null ? "неизвестно" : new Intl.DateTimeFormat("ru-RU", { timeZone: config.timezone,
    dateStyle: "short", timeStyle: "medium" }).format(ms) + ` (${config.timezone})`;
}
export function stateText(state: string, held = 0) {
  const labels: Record<string, string> = { PENDING: "ожидает отправки", SENDING: "отправляется", SENT: "отправка подтверждена",
    UNCERTAIN: "UNCERTAIN — результат неизвестен; сначала проверить Telegram", FAILED_KNOWN: "отправка отклонена",
    VALID: "принято", INVALID: "не содержит допустимого вклада", REVIEW: "требует проверки" };
  return `${labels[state] ?? state}${held && state !== "SENT" ? "; удерживается режимом тишины, требуется отдельное решение" : ""}`;
}
export function inspectText(row: Contribution, config: Config) {
  return `Накопление: ${row.source_chat_id}/${row.message_id}
Исходная дата: ${dateText(row.original_date * 1000, config)}
Состояние: ${stateText(row.source_state)} (${row.source_state})
Исходное число: ${number(row.source_amount)} мантр
Административное значение: ${row.override_amount === null ? "не установлено" : number(row.override_amount) + " мантр"}
Фактически учтено: ${number(row.effective_amount)} мантр
Редакция: ${row.is_edit ? "да" : "нет"}; дата версии: ${dateText(row.version_date * 1000, config)}
Удаление исходного сообщения не отменяет вклад.`;
}
export function adminHelp(config: Config) {
  const chat = config.allowedChatIds[0]!;
  return `Для участников
Пишите одно число за новую сессию: 1000, 1000🙏, Сегодня 1000!
Одинаковые числа в двух разных сообщениях учитываются дважды. Если ошиблись — исправьте исходное сообщение, не отправляйте повтор и не удаляйте его.
Обычное общение и медиа допустимы; подписи медиа не учитываются. Числа вне накоплений не пишите: «Мне 35 лет» тоже даст +35. Несколько чисел не складываются; бот молчит, вклад не принимается.
Старые сообщения до согласованной границы учёта не импортируются автоматически, в том числе при позднем редактировании. Проверенный исторический итог вносится отдельно ответственным.

Для ответственных (только личка)
/status — итог, остаток и проблемы; /status json — прежний машинный формат.
/silent или /silent on — прекратить все автоматические сообщения в группе. Учёт, правки, журнал и ответы в личке продолжаются. Уже разрешённый запрос в Telegram может завершиться.
/silent status — состояние, время и автор изменения.
/silent off — вернуть обычную отправку новых сообщений. Пропущенные уведомления/отчёты остаются удержаны: проверьте /reports и /notices, решайте по одному.
Пришлите ссылку на сообщение группы либо /recent (последние 20), затем «Исправить», новое число, причина. /cancel — отменить диалог.

Примеры синтаксиса: номер 123 условный, замените на проверенный номер сообщения!
/inspect ${chat} 123
/inspect ${chat} 123 json
/override ${chat} 123 0 Ошибочное начисление, сверено с участником
/release ${chat} 123 Исходная правка проверена, вернуть значение участника
/import ${chat} 124 108 2026-11-12T12:00:00+03:00 Пропуск сверён с исходным сообщением
Причина обязательна. Override приоритетнее правок участника; release снимает его. Импорт не заменяет существующую запись.

/reports — спорные и удержанные отчёты.
UNCERTAIN означает: запрос мог дойти, ответ потерян. Не повторяйте без проверки чата!
/report_sent 2026-11-12 321 Нашли публикацию 321 в группе
/report_retry 2026-11-12 Проверено отсутствие публикации, разрешить одну отправку
/notices — проблемные/удержанные уведомления (ключ для решения).
/notice_sent КЛЮЧ 322 Уведомление найдено
/notice_retry КЛЮЧ Проверено отсутствие, разрешить один повтор
SENT означает подтверждённую отправку, а не намеренную паузу. Тишина не превращает отчёты в SENT.

При сбое сохраните копию, сверяйте исходные сообщения и исправления. Не очищайте базу и очередь Telegram.
/recovery 2026-11-12T12:00:00+03:00 Время копии, требуется сверка
/reconcile Сообщения и исправления сверены после восстановления
/export — инструкция оператору. Копии и ключи не отправлять в чат; проверять восстановление отдельно. Подробности: docs/RUNBOOK.md в рабочем каталоге оператора.`;
}
